assert.equal(gesture.object(1001,900000).text_args.value,1.75,'use the recorded result rather than recomputing a distance');
assert.deepEqual(gesture.object(1001,900000).points,[{t_ms:900000,price:30},{t_ms:900000,price:33}]);
assert.equal(gesture.object(3499,900000).text_args.opacity,1);
assert.equal(gesture.object(3800,900000).text_args.opacity,.5);
assert.equal(gesture.object(4100,900000),null);
gesture.consider([{...decision,seq:2}],180999,true);assert.equal(gesture.object(180999,900000),null);
gesture.consider([{...decision,seq:3}],181000,true);assert.ok(gesture.object(181000,900000));
const disabled=new MeasurementGesture();disabled.consider([decision],1000,false);assert.equal(disabled.object(1000,900000),null);
assert.equal(JSON.stringify(decision),original,'presentation must not mutate decision geometry or data');
const budget=new VisualBudget(12,3);
assert.equal(budget.admit(Array.from({length:20},(_,i)=>({id:String(i),kind:'draw',duration:450})),0).length,3);
for(let step=1;step<10;step++)budget.admit([{id:`next${step}`,kind:'draw',duration:450}],step*1000);
assert.equal(budget.admit([{id:'over-limit',kind:'call',duration:450}],10000).length,0);
assert.equal(budget.admit([{id:'next-window',kind:'draw',duration:450}],60001).length,1);
for(const [month,hour] of [[0,13],[6,12]]){
 const open=Date.UTC(2026,month,15,hour),calendar=new SessionBoundaries();
 assert.equal(calendar.observe(open-1),null);
 assert.equal(calendar.observe(open).name,'New York','ribbon calendar respects winter/summer New York offsets');
 assert.equal(calendar.observe(open+1),null,'one scan per boundary');
 calendar.observe(open-1);assert.equal(calendar.observe(open),null,'clock reversal cannot repeat a scan');
 const reconnect=new SessionBoundaries();reconnect.observe(open-1000);reconnect.observe(open+1,false);
 assert.equal(reconnect.observe(open+2,true),null,'reconnect never triggers a missed boundary');
 assert.equal(new SessionBoundaries().observe(open+5000),null,'initial load is not a crossing');
}
