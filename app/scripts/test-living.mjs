import {build} from 'esbuild';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const bundle=await build({stdin:{contents:"export * from './src/living/Measurement';export * from './src/living/budget';export * from './src/living/SessionScan';export * from './src/living/Camera';export * from './src/living/coverageAudit';",resolveDir:process.cwd()},bundle:true,platform:'node',format:'esm',write:false});
